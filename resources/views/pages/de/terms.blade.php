<p>Alle Preise verstehen sich in Schweizer Franken (CHF) inklusive gesetzlicher Mehrwertsteuer. Versandkosten werden vor der Bestellung angezeigt. Die Zahlung erfolgt im Voraus über Stripe (TWINT, Kredit- und Debitkarten, Apple Pay, Google Pay).</p>
