<p>Les présentes CGV s'appliquent à toutes les commandes passées sur cette boutique en ligne avec une adresse de livraison en Suisse ou au Liechtenstein.</p>
<h2>1. Conclusion du contrat</h2>
<p>La présentation des produits ne constitue pas une offre ferme. En finalisant le paiement, vous passez une commande ferme. Le contrat est conclu à l'envoi de notre confirmation de commande par e-mail.</p>
<h2>2. Prix et paiement</h2>
<p>Tous les prix sont en francs suisses (CHF), TVA légale incluse. Les frais de livraison sont affichés avant la commande. Le paiement s'effectue à l'avance via Stripe (TWINT, cartes de crédit et de débit, Apple Pay, Google Pay).</p>
<h2>3. Livraison</h2>
<p>Les produits sont expédiés directement depuis les entrepôts de nos partenaires. Le délai de livraison est généralement de 7 à 15 jours ouvrables. Des retards sont possibles, notamment lors du dédouanement.</p>
<h2>4. Retours</h2>
<p>Les conditions de la page « Livraison et retours » s'appliquent.</p>
<h2>5. Garantie</h2>
<p>Si un produit est défectueux à la livraison, signalez-le dans les 14 jours avec des photos. Nous procédons, à notre choix, à un remplacement ou au remboursement du prix. Toute autre prétention est exclue dans la mesure permise par la loi.</p>
<h2>6. Protection des données</h2>
<p>Voir notre politique de protection des données.</p>
<h2>7. Droit applicable et for</h2>
<p>Le droit suisse s'applique, à l'exclusion de la Convention de Vienne (CVIM). Le for est au siège de l'exploitant de la boutique, dans la mesure permise par la loi.</p>
